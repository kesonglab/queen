// tr 返回当前语言的翻译；缺失的 key 回退到中文再回退到 key 本身。
func tr(cfg *Config, key string, args ...any) string {
	lang := "zh"
	if cfg != nil && cfg.Lang == "en" {
		lang = "en"
	}
	return trLang(lang, key, args...)
}

// trLang 按语言代码翻译（用于尚未构造 Config 的早期阶段）。
func trLang(lang, key string, args ...any) string {
	v, ok := translations[lang][key]
	if !ok || v == "" {
		v = translations["zh"][key]
		if v == "" {
			v = key
		}
	}
	if len(args) > 0 {
		return fmt.Sprintf(v, args...)
	}
	return v
}

// onOff 返回开/关文案。
func onOff(cfg *Config, b bool) string {
	if b {
		return tr(cfg, "on")
	}
	return tr(cfg, "off")
}

// langName 返回语言显示名。
func langName(code string) string {
	for _, l := range languages {
		if l.code == code {
			return l.name
		}
	}
	return code
}

// nextLang 循环切换语言。
func nextLang(cur string) string {
	for i, l := range languages {
		if l.code == cur {
			return languages[(i+1)%len(languages)].code
		}
	}
	return "zh"
}

// themeLabel 返回主题的本地化名称。
func themeLabel(cfg *Config, name string) string {
	return tr(cfg, "theme_"+name)
}

// presetLabel 返回画质预设的本地化名称。
func presetLabel(cfg *Config, name string) string {
	return tr(cfg, "preset_"+name)
}
